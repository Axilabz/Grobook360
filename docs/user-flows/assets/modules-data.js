function hasPermission(role, code) {
  if (code === null) return true;
  if (role === 'OWNER') return true;
  if (role === 'MANAGER') return MANAGER_PERMISSIONS.has(code);
  if (role === 'SALESPERSON') return SALESPERSON_PERMISSIONS.has(code);
  return false;
}

function hasAnyPermission(role, codes) {
  if (codes === null) return true;
  const list = Array.isArray(codes) ? codes : [codes];
  return list.some((c) => hasPermission(role, c));
}

