"""Supplier Management service (PROMPT-008).

Authorization is enforced by the router (require_permission) before these
methods run; this service assumes the caller is already authorized and
focuses on tenant scoping, validation, duplicate rules and concurrency —
mirroring app.services.customers.customer_service's shape exactly.
"""

import uuid
from dataclasses import dataclass

from sqlalchemy import func, or_, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.concurrency import check_row_version
from app.core.error_codes import SUPP_DUPLICATE_GSTIN, SUPP_NOT_FOUND, SUPP_VALIDATION
from app.core.exceptions import ConflictError, NotFoundError, ValidationAppError
from app.core.validators import is_valid_state_code
from app.models.supplier import Supplier
from app.services.audit.audit_service import AuditService

_MAX_CODE_ATTEMPTS = 5


@dataclass(frozen=True)
class SupplierPage:
    items: list[Supplier]
    total_items: int


def _snapshot(supplier: Supplier) -> dict:
    return {
        "name": supplier.name,
        "contact_person": supplier.contact_person,
        "phone": supplier.phone,
        "email": supplier.email,
        "gstin": supplier.gstin,
        "state_code": supplier.state_code,
        "address": supplier.address,
        "city": supplier.city,
        "pincode": supplier.pincode,
        "credit_terms_days": supplier.credit_terms_days,
    }


class SupplierService:
    def __init__(self, session: AsyncSession) -> None:
        self._session = session

    async def list_suppliers(
        self,
        *,
        tenant_id: uuid.UUID,
        page: int,
        page_size: int,
        search: str | None,
        status_filter: str | None,
        state_code_filter: str | None,
        gst_registered: bool | None,
    ) -> SupplierPage:
        base = select(Supplier).where(Supplier.tenant_id == tenant_id)

        if search:
            like = f"%{search}%"
            base = base.where(
                or_(
                    Supplier.name.ilike(like),
                    Supplier.supplier_code.ilike(like),
                    Supplier.gstin.ilike(like),
                    Supplier.phone.ilike(like),
                )
            )
        if status_filter:
            base = base.where(Supplier.status == status_filter)
        if state_code_filter:
            base = base.where(Supplier.state_code == state_code_filter)
        if gst_registered is True:
            base = base.where(Supplier.gstin.is_not(None))
        elif gst_registered is False:
            base = base.where(Supplier.gstin.is_(None))

        count_stmt = select(func.count()).select_from(base.subquery())
        total_items = (await self._session.execute(count_stmt)).scalar_one()

        paged = base.order_by(Supplier.created_at.desc()).offset((page - 1) * page_size).limit(page_size)
        items = (await self._session.execute(paged)).scalars().all()

        return SupplierPage(items=list(items), total_items=total_items)

    async def get_supplier(self, *, tenant_id: uuid.UUID, supplier_id: uuid.UUID) -> Supplier:
        result = await self._session.execute(
            select(Supplier).where(Supplier.id == supplier_id, Supplier.tenant_id == tenant_id)
        )
        supplier = result.scalar_one_or_none()
        if supplier is None:
            # Same message whether supplier_id doesn't exist at all or
            # belongs to another tenant (established pattern, PROMPT-005/007).
            raise NotFoundError("Supplier not found", code=SUPP_NOT_FOUND)
        return supplier

    async def _check_duplicate_gstin(
        self, tenant_id: uuid.UUID, gstin: str | None, *, exclude_supplier_id: uuid.UUID | None = None
    ) -> None:
        if gstin is None:
            return
        # Recommended default (prompt S24, same as Customer): no duplicate
        # ACTIVE supplier with the same GSTIN in the same tenant. Not a DB
        # constraint — Data Dictionary v3.0 defines no uniqueness on gstin.
        stmt = select(Supplier).where(
            Supplier.tenant_id == tenant_id, Supplier.gstin == gstin, Supplier.status == "ACTIVE"
        )
        if exclude_supplier_id is not None:
            stmt = stmt.where(Supplier.id != exclude_supplier_id)
        existing = (await self._session.execute(stmt)).scalars().first()
        if existing is not None:
            raise ConflictError("A supplier with this GSTIN already exists.", code=SUPP_DUPLICATE_GSTIN)

    async def _next_supplier_code(self, tenant_id: uuid.UUID, attempt: int) -> str:
        # supplier_code is not defined as system- vs. user-generated by any
        # approved source (open decision — see PROMPT-008-NOTES.md), same
        # judgment call made for customer_code in PROMPT-007.
        count_stmt = select(func.count(Supplier.id)).where(Supplier.tenant_id == tenant_id)
        count = (await self._session.execute(count_stmt)).scalar_one()
        return f"SUPP-{count + 1 + attempt:04d}"

    async def create_supplier(
        self,
        *,
        tenant_id: uuid.UUID,
        actor_user_id: uuid.UUID,
        name: str,
        contact_person: str,
        phone: str,
        email: str | None,
        gstin: str | None,
        state_code: str | None,
        address: str | None,
        city: str | None,
        pincode: str | None,
        credit_terms_days: int,
        ip_address: str | None,
    ) -> Supplier:
        await self._check_duplicate_gstin(tenant_id, gstin)

        last_error: Exception | None = None
        for attempt in range(_MAX_CODE_ATTEMPTS):
            code = await self._next_supplier_code(tenant_id, attempt)
            supplier = Supplier(
                tenant_id=tenant_id,
                supplier_code=code,
                name=name,
                contact_person=contact_person,
                phone=phone,
                email=email,
                gstin=gstin,
                state_code=state_code,
                address=address,
                city=city,
                pincode=pincode,
                credit_terms_days=credit_terms_days,
                created_by=actor_user_id,
                updated_by=actor_user_id,
            )
            try:
                async with self._session.begin_nested():
                    self._session.add(supplier)
                    await self._session.flush()
                break
            except IntegrityError as exc:
                last_error = exc
                continue
        else:
            raise ConflictError("Could not allocate a unique supplier code. Please retry.") from last_error

        await AuditService(self._session).record(
            tenant_id=tenant_id,
            actor_user_id=actor_user_id,
            action="SUPPLIER_CREATED",
            entity_type="supplier",
            entity_id=supplier.id,
            after=_snapshot(supplier),
            ip_address=ip_address,
        )
        return supplier

    async def update_supplier(
        self,
        *,
        tenant_id: uuid.UUID,
        actor_user_id: uuid.UUID,
        supplier_id: uuid.UUID,
        expected_row_version: int,
        ip_address: str | None,
        **fields,
    ) -> Supplier:
        supplier = await self.get_supplier(tenant_id=tenant_id, supplier_id=supplier_id)
        check_row_version(supplier, expected_row_version)
        before = _snapshot(supplier)

        gstin = fields.get("gstin", ...)
        state_code = fields.get("state_code", ...)
        effective_gstin = supplier.gstin if gstin is ... else gstin
        effective_state_code = supplier.state_code if state_code is ... else state_code
        if effective_gstin is not None:
            gstin_state = effective_gstin[:2]
            if effective_state_code is None:
                effective_state_code = gstin_state
            elif effective_state_code != gstin_state:
                raise ValidationAppError(
                    "State does not match the state encoded in the GSTIN", code=SUPP_VALIDATION
                )
        elif effective_state_code is not None and not is_valid_state_code(effective_state_code):
            raise ValidationAppError("Invalid state code", code=SUPP_VALIDATION)

        if effective_gstin != supplier.gstin:
            await self._check_duplicate_gstin(tenant_id, effective_gstin, exclude_supplier_id=supplier.id)

        supplier.gstin = effective_gstin
        supplier.state_code = effective_state_code

        for field_name in ("name", "contact_person", "phone", "email", "address", "city", "pincode", "credit_terms_days"):
            value = fields.get(field_name, ...)
            if value is not ...:
                setattr(supplier, field_name, value)

        supplier.updated_by = actor_user_id
        supplier.row_version += 1
        await self._session.flush()

        await AuditService(self._session).record(
            tenant_id=tenant_id,
            actor_user_id=actor_user_id,
            action="SUPPLIER_UPDATED",
            entity_type="supplier",
            entity_id=supplier.id,
            before=before,
            after=_snapshot(supplier),
            ip_address=ip_address,
        )
        return supplier

    async def _set_status(
        self,
        *,
        tenant_id: uuid.UUID,
        actor_user_id: uuid.UUID,
        supplier_id: uuid.UUID,
        new_status: str,
        expected_row_version: int,
        ip_address: str | None,
    ) -> Supplier:
        supplier = await self.get_supplier(tenant_id=tenant_id, supplier_id=supplier_id)
        check_row_version(supplier, expected_row_version)

        previous_status = supplier.status
        supplier.status = new_status
        supplier.updated_by = actor_user_id
        supplier.row_version += 1
        await self._session.flush()

        await AuditService(self._session).record(
            tenant_id=tenant_id,
            actor_user_id=actor_user_id,
            action="SUPPLIER_ACTIVATED" if new_status == "ACTIVE" else "SUPPLIER_DEACTIVATED",
            entity_type="supplier",
            entity_id=supplier.id,
            before={"status": previous_status},
            after={"status": new_status},
            ip_address=ip_address,
        )
        return supplier

    async def activate_supplier(self, **kwargs) -> Supplier:
        return await self._set_status(new_status="ACTIVE", **kwargs)

    async def deactivate_supplier(self, **kwargs) -> Supplier:
        return await self._set_status(new_status="INACTIVE", **kwargs)
